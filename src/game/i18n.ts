export const STRINGS: Record<Lang, Record<string, string>> = { fa, en };

export function t(lang: Lang, key: string): string {
  return STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
}

const FA_DIGITS = ["۰", "۱", "۲", "۳", "۴", "۵", "۶", "۷", "۸", "۹"];

/** Locale-correct digits: Persian numerals in fa, Western in en. */
export function fmtNum(lang: Lang, n: number): string {
  const s = String(n);
  if (lang === "fa") return s.replace(/\d/g, (d) => FA_DIGITS[Number(d)]);
  return s;
}

